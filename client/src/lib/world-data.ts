/**
 * Мини-данные для рендера карты мира.
 *
 *  - continents: упрощённые SVG-пути в системе равнопромежуточной (equirectangular)
 *    проекции с viewBox 1000×500. Долгота -180..180 → x 0..1000, широта 90..-90 → y 0..500.
 *  - countryCenter: широта/долгота центра страны (берём столицу или геоцентр).
 *
 * Контуры континентов — стилизованные. Это не геополитически точная карта,
 * а декоративная подложка под точки серверов.
 */

export const MAP_W = 1000;
export const MAP_H = 500;

/** Equirectangular projection. */
export function project(lat: number, lng: number): { x: number; y: number } {
  return {
    x: ((lng + 180) / 360) * MAP_W,
    y: ((90 - lat) / 180) * MAP_H,
  };
}

